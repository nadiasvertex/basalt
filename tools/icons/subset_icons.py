#!/usr/bin/env python3
"""Builds Basalt's icon font and the C++ tables that name its glyphs.

Usage: subset_icons.py <phosphor-web-release-dir>

Reads tools/icons/icons.txt and the regular-weight font and stylesheet from a release of
https://github.com/phosphor-icons/web (v2.1.2 at the time of writing; MIT license). Needs the
Python package fonttools. Writes:

  third_party/phosphor/Phosphor.ttf      the font with only the listed glyphs
  third_party/phosphor/LICENSE           the license of the release
  generated/basalt/icon_ids.h            the basalt::icon enumeration
  src/basalt/icon_table.inc              name and codepoint of each icon
  src/basalt/icon_font.inc               the bytes of Phosphor.ttf
"""
import re
import shutil
import sys
from pathlib import Path

from fontTools import subset

ROOT = Path(__file__).resolve().parents[2]


def read_icons(path):
    rows = []
    for line in path.read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            enum_name, phosphor_name = line.split()
            rows.append((enum_name, phosphor_name))
    return rows


def read_codepoints(stylesheet):
    pattern = re.compile(r'\.ph\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"')
    return {name: int(code, 16) for name, code in pattern.findall(stylesheet.read_text())}


def subset_font(source, destination, codepoints):
    options = subset.Options()
    options.layout_features = []  # Icons are one codepoint each; there are no ligatures.
    options.hinting = False
    options.notdef_outline = True
    options.name_IDs = [1, 2, 4, 6]
    font = subset.load_font(str(source), options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    subset.save_font(font, str(destination), options)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    release = Path(sys.argv[1]) / "src" / "regular"
    icons = read_icons(ROOT / "tools/icons/icons.txt")
    available = read_codepoints(release / "style.css")
    missing = [phosphor for _, phosphor in icons if phosphor not in available]
    if missing:
        sys.exit("not in this Phosphor release: " + ", ".join(missing))
    rows = [(enum_name, phosphor, available[phosphor]) for enum_name, phosphor in icons]
    if len({code for _, _, code in rows}) != len(rows) or len({n for n, _, _ in rows}) != len(rows):
        sys.exit("icons.txt repeats a name or an icon")

    font_path = ROOT / "third_party/phosphor/Phosphor.ttf"
    font_path.parent.mkdir(parents=True, exist_ok=True)
    subset_font(release / "Phosphor.ttf", font_path, [code for _, _, code in rows])
    shutil.copyfile(release.parents[1] / "LICENSE", font_path.parent / "LICENSE")

    ids = ["  none,"] + [f"  {name}," for name, _, _ in rows]
    write(ROOT / "generated/basalt/icon_ids.h", "\n".join([
        "#pragma once",
        "",
        "// Generated by tools/icons/subset_icons.py from tools/icons/icons.txt. Do not edit.",
        "",
        "#include <cstdint>",
        "",
        "namespace basalt {",
        "",
        "enum class icon : std::uint8_t {",
        *ids,
        "};",
        "",
        "} // namespace basalt",
        "",
    ]))
    write(ROOT / "src/basalt/icon_table.inc", "".join(
        f'{{icon::{name}, "{name}", 0x{code:04X}}},\n' for name, _, code in rows))
    data = font_path.read_bytes()
    write(ROOT / "src/basalt/icon_font.inc", "".join(
        ",".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",\n" for i in range(0, len(data), 16)))
    print(f"{len(rows)} icons, {len(data)} bytes of font")


main()
